#!/usr/bin/env node
// Full placeholder BODY PART SET for the rig, painted in code (sprite-making painter): one part around every rotating joint, so the
// skeleton can bend at the neck, shoulders, elbows, waist, hips, knees and ankles. Real parts (SPRITES.md #106-#108) replace these by
// file name; manifest.json lists each part's joint pivot and bone length.
//   node scripts/make-body-parts.mjs [outDir]      (default client/public/rig/parts/bodyset/)
// Contract for every part: side view facing RIGHT, drawn STRAIGHT (limbs hang down, torso / head point up), joint cap rounded and bigger than
// the limb so a swing never opens a gap, 2 px dark rim, soft shading from the upper left. Also writes parts-sheet.png: all parts in
// 128 x 128 cells (the layout asked of ChatGPT in SPRITES.md).
import { mkdirSync, writeFileSync } from "node:fs";
import { Canvas, M } from "./lib/paint.mjs";
import { writePNG } from "./lib/png.mjs";

const out = process.argv[2] || new URL("../client/public/rig/parts/bodyset/", import.meta.url).pathname;
mkdirSync(out, { recursive: true });
const SKIN = "#e0ad7c", CREAM = "#dcc7a0", VEST = "#8c8672", PANTS = "#55505a", BOOT = "#7a4a2c", LEATHER = "#6a4228", HAIR = "#6a4a2e";
const manifest = { set: "bodyset", note: "generated by scripts/make-body-parts.mjs", parts: {}, soleBelowAnkle: 11 };
const cells = [];
function part(name, w, h, pivot, len, joint, draw) {
  const c = new Canvas(w, h); draw(c); const png = c.png();
  c.save(out + name + ".png"); manifest.parts[name] = { file: name + ".png", pivot, len, joint, size: [w, h] }; cells.push({ name, png, pivot });
}

// ---- spine: pelvis (root), torso (waist joint), head + neck (neck joint)
part("pelvis", 32, 22, [16, 8], 0, "root / hips", (c) => {
  c.shape({ rect: [3, 3, 26, 15, 6.5] }, { ...M.cloth(PANTS), round: 5.5, rim: 2 });
  c.shape({ rect: [3, 3, 26, 4.2, 2] }, { ...M.leather(LEATHER), round: 2, rim: 1.6 });
  c.flat({ line: [20, 9, 20, 16, 1.4] }, "#8a8590", 0.28);
});
part("torso", 36, 44, [18, 38], 25, "waist", (c) => {
  c.shape({ poly: [[7, 38], [5.5, 24], [7, 11], [13, 4.5], [24, 4.5], [30, 11], [31, 25], [29, 38]] }, { ...M.cloth(CREAM), round: 7, rim: 2 });       // shirt
  c.shape({ poly: [[8.5, 38], [8, 22], [10.5, 11], [15, 7.5], [22, 7.5], [25.5, 13], [26.5, 38]] }, { ...M.cloth(VEST), round: 5, rim: 1.7 });          // vest
  c.shape({ rect: [5.5, 32.5, 25, 4.6, 1.8] }, { ...M.leather(LEATHER), round: 2, rim: 1.6 });                                                           // belt
  c.shape({ rect: [22.4, 33, 4.4, 3.6, 0.8] }, { ...M.gold(), round: 1.2, rim: 1 });                                                                      // buckle
  c.shape({ ellipse: [18, 8, 9, 6] }, { ...M.cloth(CREAM), round: 4, rim: 1.8 });                                                                          // shoulder / collar mass: the arm cap sits over it
  c.flat({ line: [14, 14, 14, 30, 1.3] }, "#fff3d8", 0.25);
});
part("head", 42, 40, [19, 34], 0, "neck", (c) => {
  c.shape({ capsule: [19, 27, 19, 35.5, 4.4, 4.8] }, { ...M.skin(SKIN), dark: "#b57d55", round: 4, rim: 2 });                                              // neck
  c.shape({ ellipse: [19.5, 17, 12, 13] }, { ...M.skin(SKIN), round: 8, rim: 2 });                                                                         // skull
  c.shape({ ellipse: [25, 24.5, 8.2, 8.6] }, { ...M.skin(SKIN), round: 6, rim: 0.001 });                                                                   // jaw and chin
  c.shape({ ellipse: [14, 19, 2.7, 3.8] }, { ...M.skin(SKIN), dark: "#b57d55", round: 2, rim: 1.4 });                                                      // ear
  c.shape({ ellipse: [31.8, 21.5, 2.7, 2.3] }, { ...M.skin(SKIN), round: 2, rim: 1.2 });                                                                   // nose
  c.flat({ ellipse: [25.5, 17.2, 2.7, 3.1] }, "#ffffff", 1); c.flat({ ellipse: [26.4, 17.6, 1.5, 2.1] }, "#2a1a12", 1);                                      // eye
  c.flat({ line: [22, 13.2, 29.5, 12.4, 1.5] }, "#4a2f1c", 0.9);                                                                                           // brow
  c.flat({ line: [25, 29, 29.5, 28.4, 1.1] }, "#7a3a30", 0.9);                                                                                             // mouth
});
part("hair", 42, 40, [19, 34], 0, "neck (overlay)", (c) => {      // grey-scale in the real set (tinted in code); brown here
  const cap = { ellipse: [18.5, 13.5, 13.8, 12.6] }, face = { ellipse: [30, 26, 9, 12] };
  c.shape({ union: [{ sub: [cap, face] }, { ellipse: [11.5, 19.5, 6.2, 8.5] }] }, { ...M.hair(HAIR), round: 5.5, rim: 2 });
  c.flat({ ellipse: [17, 5.8, 6.5, 1.8] }, "#c9a070", 0.5); c.flat({ line: [13, 9, 24, 8, 1.1] }, "#3a2616", 0.5);
});

// ---- arm: shoulder + upper arm, elbow + forearm + hand
part("upperArm", 24, 30, [12, 9], 13, "shoulder", (c) => {
  c.shape({ union: [{ capsule: [12, 9, 12, 21, 5.8, 4.9] }, { ellipse: [12, 9, 7.4, 7.2] }] }, { ...M.cloth(CREAM), round: 5, rim: 2 });
  c.flat({ line: [14.6, 11, 14.6, 20, 1.3] }, "#fff3d8", 0.32);
  c.shape({ capsule: [12, 19.5, 12, 22, 5.2, 5.2] }, { ...M.cloth("#c9b48c"), round: 1.5, rim: 1.4 });                                                       // cuff
});
part("foreArm", 22, 34, [11, 8], 13, "elbow", (c) => {
  c.shape({ ellipse: [11, 8, 6, 5.8] }, { ...M.cloth(CREAM), round: 4.5, rim: 2 });                                                                        // elbow cap (sleeve)
  c.shape({ capsule: [11, 9, 11, 21, 4.9, 4.2] }, { ...M.skin(SKIN), round: 4, rim: 2 });                                                                  // forearm
  c.shape({ capsule: [11, 12, 11, 17.5, 5.5, 5.5] }, { ...M.leather(LEATHER), round: 3, rim: 1.7 });                                                       // bracer
  c.shape({ ellipse: [11.4, 24.5, 4.8, 5.4] }, { ...M.skin(SKIN), round: 4, rim: 2 });                                                                     // hand
  c.shape({ ellipse: [14.4, 23.4, 1.8, 2.6] }, { ...M.skin(SKIN), round: 1.5, rim: 1.2 });                                                                 // thumb
});

// ---- leg: hip + femur, knee + shin, ankle + foot
part("thigh", 28, 32, [14, 9], 14, "hip", (c) => {
  c.shape({ union: [{ capsule: [14, 9, 14, 22, 7.2, 6]  }, { ellipse: [14, 9, 7.8, 7.6] }] }, { ...M.cloth(PANTS), round: 5.5, rim: 2 });
  c.flat({ line: [16.6, 12, 16.6, 21, 1.5] }, "#8a8590", 0.3);
});
part("shin", 24, 28, [12, 8], 10, "knee", (c) => {
  c.shape({ union: [{ capsule: [12, 8, 12, 14.5, 5.9, 5.3] }, { ellipse: [12, 8, 6.2, 6] }, { ellipse: [10, 12.5, 5.2, 4] }] }, { ...M.cloth(PANTS), round: 4.5, rim: 2 });   // knee cap + calf
  c.shape({ capsule: [12, 12.5, 12, 19.5, 5.3, 4.7] }, { ...M.leather(BOOT), round: 3.5, rim: 2 });                                                          // boot shaft
  c.flat({ line: [7.2, 12.6, 16.8, 12.6, 1.2] }, "#2a1a10", 0.7);                                                                                          // cuff line
});
part("foot", 32, 20, [9, 4], 0, "ankle", (c) => {
  c.shape({ poly: [[3.5, 3], [14.5, 3], [22, 6.5], [27, 9.5], [28.5, 13], [26, 16], [3.5, 16]] }, { ...M.leather(BOOT), round: 4, rim: 2 });
  c.flat({ line: [4.5, 14.6, 26, 14.6, 1.4] }, "#2a1a10", 0.85);                                                                                           // sole
  c.flat({ line: [23, 7.5, 26.5, 10.5, 1] }, "#4a2a18", 0.5);                                                                                              // toe seam
});
writeFileSync(out + "manifest.json", JSON.stringify(manifest, null, 1));

// ---- parts-sheet.png: 128 x 128 cells, 4 columns, each part centred with its pivot's x on the cell centre and its joint 20 px from the top
const COLS = 4, CELL = 128, rows = Math.ceil(cells.length / COLS), W = COLS * CELL, H = rows * CELL, data = new Uint8Array(W * H * 4);
cells.forEach((cell, i) => {
  const ox = (i % COLS) * CELL + Math.round(CELL / 2 - cell.pivot[0]), oy = Math.floor(i / COLS) * CELL + 12;          // every part: top of its canvas 12 px below the cell top, pivot column centred
  for (let y = 0; y < cell.png.h; y++) for (let x = 0; x < cell.png.w; x++) { const s = (y * cell.png.w + x) * 4, dx = ox + x, dy = oy + y; if (dx < 0 || dy < 0 || dx >= W || dy >= H) continue; for (let k = 0; k < 4; k++) data[(dy * W + dx) * 4 + k] = cell.png.data[s + k]; }
});
writePNG(out + "parts-sheet.png", { w: W, h: H, data });
console.log("wrote", Object.keys(manifest.parts).join(", "), "->", out);
