#!/usr/bin/env node
// Placeholder rig parts (arms and legs) painted in code with the sprite-making painter, so the rig can be built, animated and refined
// before the real parts (SPRITES.md #106) arrive. Real parts replace these PNGs by file name; manifest.json lists the joint pivots.
//   node scripts/make-placeholder-rig-parts.mjs [outDir]
// Every limb is drawn straight, hanging down, side view facing right, joint cap at the top (the same contract as the real parts).
import { mkdirSync, writeFileSync } from "node:fs";
import { Canvas, M } from "./lib/paint.mjs";

const out = process.argv[2] || new URL("../client/public/rig/parts/placeholder/", import.meta.url).pathname;
mkdirSync(out, { recursive: true });
const manifest = { set: "placeholder", note: "generated by scripts/make-placeholder-rig-parts.mjs", parts: {} };
const SKIN = "#e0ad7c", SLEEVE = "#dcc7a0", PANTS = "#55505a", BOOT = "#7a4a2c", LEATHER = "#6a4228";
// a part: canvas w x h, pivot = the joint centre; len = bone length to the next joint
function part(name, w, h, pivot, len, draw) { const c = new Canvas(w, h); draw(c); c.save(out + name + ".png"); manifest.parts[name] = { file: name + ".png", pivot, len, size: [w, h] }; }

// Proportions of the hero (98 px person: head ~30, torso 31, legs ~31): thigh 14 + shin 10 + 7 below the ankle; arm 13 + 13 + hand.
part("upperArm", 20, 26, [10, 8], 13, (c) => {
  c.shape({ union: [{ capsule: [10, 8, 10, 19, 5.6, 4.8] }, { ellipse: [10, 8, 6.4, 6.4] }] }, { ...M.cloth(SLEEVE), round: 4.5, rim: 2 });
  c.flat({ line: [12.4, 10, 12.4, 18, 1.3] }, "#fff3d8", 0.35);
});
part("foreArm", 20, 28, [10, 7], 13, (c) => {
  c.shape({ capsule: [10, 7, 10, 17.5, 4.6, 4.1] }, { ...M.skin(SKIN), round: 4, rim: 2 });
  c.shape({ capsule: [10, 8.5, 10, 13.5, 5.2, 5.2] }, { ...M.leather(LEATHER), round: 3, rim: 1.8 });     // bracer
  c.shape({ ellipse: [10.4, 20, 4.5, 5] }, { ...M.skin(SKIN), round: 4, rim: 2 });                        // hand
});
part("thigh", 24, 28, [12, 8], 14, (c) => {
  c.shape({ union: [{ capsule: [12, 8, 12, 20, 6.6, 5.6] }, { ellipse: [12, 8, 7, 7] }] }, { ...M.cloth(PANTS), round: 5, rim: 2 });
  c.flat({ line: [14.4, 11, 14.4, 19, 1.5] }, "#8a8590", 0.3);
});
// shin: trouser leg continuing the thigh (no knee ball), a boot shaft below it; the FOOT is its own part so the sole can stay flat
part("shin", 22, 24, [11, 7], 10, (c) => {
  c.shape({ union: [{ capsule: [11, 7, 11, 13, 5.6, 5] }, { ellipse: [11, 7, 5.8, 5.8] }] }, { ...M.cloth(PANTS), round: 4, rim: 2 });
  c.shape({ capsule: [11, 11.5, 11, 17, 5.2, 4.6] }, { ...M.leather(BOOT), round: 3.5, rim: 2 });
});
part("foot", 30, 18, [9, 4], 0, (c) => {                                  // pivot = the ankle; toe points right; the sole is 7 px below the ankle
  c.shape({ poly: [[4, 3], [14, 3], [22, 6.5], [26.5, 9], [27, 12.5], [25, 15], [4, 15]] }, { ...M.leather(BOOT), round: 3.5, rim: 2 });
  c.flat({ line: [5, 13.6, 25, 13.6, 1.3] }, "#2a1a10", 0.8);
});
manifest.parts.foot = manifest.parts.foot;
manifest.soleBelowAnkle = 11;            // foot part: the sole is 11 px below its ankle pivot (pivot y 4, sole y 15)
writeFileSync(out + "manifest.json", JSON.stringify(manifest, null, 1));
console.log("wrote", Object.keys(manifest.parts).join(", "), "->", out);
